"""Zed (gpui): theme_overrides for the active theme in settings.json, no shim.

For each installed Zed (native: $XDG_CONFIG_HOME/zed; flatpak dev.zed.Zed:
~/.var/app/dev.zed.Zed/config/zed), settings.json (edited, backed up; Zed
hot-reloads it) gets one ``"theme_overrides"`` entry, between two
``// appglass:`` comment lines right after the opening brace, for the theme
Zed uses in the DMS mode (``theme`` as a name, or its ``dark`` / ``light``
half; One Dark / One Light when unset). The keys (B5b):

- background.appearance transparent; background = surface at the content
  level (the one fill under every pane);
- title_bar, title_bar inactive and status_bar = surface at the bar level:
  Zed paints them beside ``background``, not over it, so a clear one is a
  hole (B5b first pass: alpha 0);
- every other full-area surface (editor, gutter, subheader, panel, tab bar,
  toolbar, inactive tab, terminal, surface, scrollbar track) clear, so
  nothing stacks on the fill;
- the active tab, the active line and the element / ghost element
  hover / selected / active states as light overlays (One Dark's opaque
  selection painted 255 blocks);
- elevated_surface = surface_container, opaque: palettes, menus and modals
  stay solid.

The block is rebuilt on every apply (new DMS colours land even after the
user edited the file elsewhere) and taken out by remove; the rest of the file,
comments included, is the user's. A ``theme_overrides`` of the user's own
outside the block is not merged into (skipped with a warning: one key twice
is ambiguous); a settings.json that is not JSON with comments is skipped.
niri: ``^dev\\.zed\\.Zed$`` gets opacity 1.0: Zed paints its own alpha.
"""

import json
import os
import re

from . import _term
from ..core import Conflict, alpha_hex, norm_hex

NAME = "zed"
APP_IDS = [r"^dev\.zed\.Zed(-Preview)?$"]
FLATPAK = "dev.zed.Zed"
CMDS = ("zed", "zeditor", "zedit", "zed-editor")
BEGIN = "// appglass: begin. Generated by appglass apply, removed by appglass remove."
END = "// appglass: end"
DEFAULT_THEME = {"dark": "One Dark", "light": "One Light"}
CLEAR = "#00000000"
CLEAR_KEYS = (
    "editor.background", "editor.gutter.background", "editor.subheader.background",
    "panel.background", "tab_bar.background", "toolbar.background",
    "tab.inactive_background", "terminal.background", "surface.background",
    "scrollbar.track.background",
)
# overlay alpha per state over the glass (white on dark, black on light)
OVERLAYS = {
    "tab.active_background": 0x0d, "editor.active_line.background": 0x0d,
    "element.hover": 0x14, "element.selected": 0x1f, "element.active": 0x24,
    "ghost_element.hover": 0x14, "ghost_element.selected": 0x1f,
    "ghost_element.active": 0x24,
}


def installed(env):
    return bool(_term.targets(env, CMDS, FLATPAK))


# ---------------------------------------------------------------- JSON with comments

def strip_jsonc(text):
    """text without // and /* */ comments and trailing commas (strings kept)."""
    out, i, n = [], 0, len(text)
    while i < n:
        c = text[i]
        if c == '"':
            j = i + 1
            while j < n and text[j] != '"':
                j += 2 if text[j] == "\\" else 1
            out.append(text[i:j + 1])
            i = j + 1
        elif text.startswith("//", i):
            j = text.find("\n", i)
            i = n if j < 0 else j
        elif text.startswith("/*", i):
            j = text.find("*/", i + 2)
            i = n if j < 0 else j + 2
        else:
            out.append(c)
            i += 1
    return re.sub(r",(\s*[}\]])", r"\1", "".join(out))


def parse(text, path):
    if not text.strip():
        return {}
    try:
        obj = json.loads(strip_jsonc(text))
    except ValueError:
        raise Conflict("%s is not JSON (with comments); left untouched" % path)
    if not isinstance(obj, dict):
        raise Conflict("%s is not a JSON object; left untouched" % path)
    return obj


def drop_block(text):
    out, inside = [], False
    for ln in text.splitlines(keepends=True):
        s = ln.strip()
        if s == BEGIN:
            inside = True
            continue
        if inside:
            if s == END:
                inside = False
            continue
        out.append(ln)
    # no end marker (cut by hand): skipping to EOF would drop the user's keys
    if inside:
        raise Conflict("appglass begin line has no end line; left untouched")
    return "".join(out)


def _code_start(text):
    """Index of the top-level '{' (comments before it skipped), or -1."""
    i, n = 0, len(text)
    while i < n:
        if text[i].isspace():
            i += 1
        elif text.startswith("//", i):
            j = text.find("\n", i)
            i = n if j < 0 else j
        elif text.startswith("/*", i):
            j = text.find("*/", i + 2)
            i = n if j < 0 else j + 2
        else:
            return i if text[i] == "{" else -1
    return -1


# ---------------------------------------------------------------- the overrides

def theme_name(settings, mode):
    t = settings.get("theme")
    if isinstance(t, str) and t:
        return t
    if isinstance(t, dict) and isinstance(t.get(mode), str) and t.get(mode):
        return t[mode]
    return DEFAULT_THEME[mode]


def overrides(ctx):
    lv = ctx.levels
    surface = norm_hex(ctx.colors("surface"))
    ink = "#ffffff" if ctx.mode != "light" else "#000000"
    o = {
        "background.appearance": "transparent",
        "background": surface + alpha_hex(lv.content),
        "title_bar.background": surface + alpha_hex(lv.bar),
        "title_bar.inactive_background": surface + alpha_hex(lv.bar),
        "status_bar.background": surface + alpha_hex(lv.bar),
    }
    for k in CLEAR_KEYS:
        o[k] = CLEAR
    for k, a in OVERLAYS.items():
        o[k] = "%s%02x" % (ink, a)
    o["elevated_surface.background"] = norm_hex(ctx.colors("surface_container")) + "ff"
    return o


def block(name, values, comma):
    body = json.dumps({"theme_overrides": {name: values}}, indent=2)
    inner = body.strip()[1:-1].strip("\n")         # '  "theme_overrides": {...}'
    return "  %s\n%s%s\n  %s\n" % (BEGIN, inner, "," if comma else "", END)


def edit(ctx, text, path):
    base = drop_block(text)
    settings = parse(base, path)
    if "theme_overrides" in settings:
        raise Conflict("%s already has a theme_overrides of its own; left untouched (move "
                       "it out to let appglass write the glass one)" % path)
    name = theme_name(settings, "light" if ctx.mode == "light" else "dark")
    if not base.strip():
        return "{\n%s}\n" % block(name, overrides(ctx), False)
    at = _code_start(base)
    if at < 0:
        raise Conflict("%s: no top-level object; left untouched" % path)
    rest = strip_jsonc(base[at + 1:]).lstrip()
    comma = not rest.startswith("}")
    head = base[:at + 1]
    tail = base[at + 1:]
    if tail.startswith("\n"):
        tail = tail[1:]
    return head + "\n" + block(name, overrides(ctx), comma) + tail


def undo(env, path, text):
    out = drop_block(text)
    # an object appglass created holds nothing else: back to empty
    if strip_jsonc(out).strip() in ("{}", "{\n}"):
        return ""
    return out


def apply(ctx):
    paths = []
    for t in _term.targets(ctx.env, CMDS, FLATPAK):
        p = t.config_path("zed", "settings.json")
        if os.path.islink(p):
            raise Conflict("%s is a symlink (user-managed); left untouched" % p)
        edit(ctx, ctx.read_text(p) or "", p)      # a Conflict before anything is written
        ctx.edit_text(p, lambda text, q=p: edit(ctx, text, q),
                      undo=lambda text, q=p: undo(ctx.env, q, text))
        paths.append(p)
    return paths
