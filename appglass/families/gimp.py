"""GIMP 3: a user gimp.css block that turns GIMP's own theme into glass.

GTK_THEME never reaches GIMP: it loads its theme.css over the GTK theme
(B5b). GIMP imports $XDG_CONFIG_HOME/GIMP/<major.minor>/gimp.css last, and
the flatpak org.gimp.GIMP maps xdg-config/GIMP to that same host dir, so one
file serves a native and a flatpak GIMP.

gimp.css (edited, backed up; a marked block at the end, the user's own rules
kept): the theme's bg-color and extreme-bg-color made transparent (each
nested container paints them: an alpha there stacks to 255), widget-bg-color
at 0.45, one painted layer (.background, window, dialog) at the content
level, headerbars at the bar level, menus, popovers, tooltips and the combo
popup opaque. The colours are GIMP's own for its colour scheme (gimprc
``theme-color-scheme``: the rgb literals of the Default theme's
gimp-<scheme>.css), so its text keeps its contrast. The canvas image is
never touched (it stays opaque by design).

The version dir is picked from the installed GIMP (``gimp --version``, the
flatpak metainfo), else the newest dir already there; a GIMP minor update
is a new dir (re-apply writes it). niri: ``^org\\.gimp\\.GIMP$`` and
``^gimp$`` get opacity 1.0.
"""

import glob
import os
import re

from ..core import Conflict, rgba

NAME = "gimp"
APP_IDS = [r"^org\.gimp\.GIMP$", r"^gimp$"]
FLATPAK = "org.gimp.GIMP"
CMDS = ("gimp", "gimp-3", "gimp-3.0", "gimp-3.2")
BEGIN = "/* appglass: begin. Generated by appglass apply, removed by appglass remove. */"
END = "/* appglass: end */"
# Default theme literals (GIMP 3.2) when the theme files are not readable
SCHEMES = {
    "dark": {"bg-color": "#3c3c3c", "widget-bg-color": "#2a2a2a"},
    "gray": {"bg-color": "#777777", "widget-bg-color": "#646464"},
    "light": {"bg-color": "#ebebeb", "widget-bg-color": "#dcdcdc"},
}


def _ver(s):
    m = re.search(r"\b(\d+)\.(\d+)(?:\.\d+)?\b", s or "")
    return "%s.%s" % m.groups() if m else None


def _flatpak(env):
    from .. import detect
    return detect.flatpak_app(env, FLATPAK)


def installed(env):
    return any(env.which(c) for c in CMDS) or _flatpak(env) is not None


def theme_dirs(env):
    """Where the Default theme of the installed GIMPs lives."""
    out = []
    info = _flatpak(env)
    if info:
        out += glob.glob(os.path.join(info["files"], "share", "gimp", "*", "themes", "Default"))
    from .. import detect
    for d in detect.data_dirs(env):
        out += glob.glob(os.path.join(d, "gimp", "*", "themes", "Default"))
    return out


def versions(env):
    vs = []
    for c in CMDS:
        exe = env.which(c)
        if exe:
            try:
                r = env.run([exe, "--version"], timeout=20)
                v = _ver(r.stdout + r.stderr)
            except Exception:
                v = None
            if v:
                vs.append(v)
            break
    info = _flatpak(env)
    if info:
        meta = os.path.join(info["files"], "share", "metainfo", FLATPAK + ".metainfo.xml")
        try:
            with open(meta, encoding="utf-8", errors="replace") as f:
                m = re.search(r'<release[^>]*\bversion="([^"]+)"', f.read())
            if m and _ver(m.group(1)):
                vs.append(_ver(m.group(1)))
        except OSError:
            pass
    if not vs:
        have = [os.path.basename(d) for d in glob.glob(os.path.join(env.config_home, "GIMP", "*"))
                if re.match(r"^\d+\.\d+$", os.path.basename(d))]
        if have:
            vs.append(max(have, key=lambda v: tuple(map(int, v.split(".")))))
    return sorted(set(vs))


def scheme(text):
    """gimprc (theme-color-scheme X), else (prefer-dark-theme no) -> light, else dark."""
    m = re.search(r"\(theme-color-scheme\s+\"?([a-z-]+)\"?\)", text or "")
    if m and m.group(1) in SCHEMES:
        return m.group(1)
    if re.search(r"\(prefer-dark-theme\s+no\)", text or ""):
        return "light"
    return "dark"


def _rgb(s):
    m = re.match(r"rgba?\(\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)", s.strip())
    return "#%02x%02x%02x" % tuple(int(x) for x in m.groups()) if m else None


def colours(env, sch):
    out = dict(SCHEMES[sch])
    for d in theme_dirs(env):
        try:
            with open(os.path.join(d, "gimp-%s.css" % sch), encoding="utf-8") as f:
                text = f.read()
        except OSError:
            continue
        for k in out:
            m = re.search(r"@define-color\s+%s\s+([^;]+);" % re.escape(k), text)
            c = _rgb(m.group(1)) if m else None
            if c:
                out[k] = c
        break
    return out


def block(ctx, col):
    lv = ctx.levels
    bg, wbg = col["bg-color"], col["widget-bg-color"]
    return "\n".join([
        BEGIN,
        "/* GIMP's theme as glass: one painted layer at the content level, popups opaque. */",
        "@define-color bg-color transparent;",
        "@define-color extreme-bg-color transparent;",
        "@define-color widget-bg-color %s;" % rgba(wbg, 0.45),
        ".background, window, dialog { background-color: %s; }" % rgba(bg, lv.content),
        "headerbar, .titlebar { background-color: %s; background-image: none; }" % rgba(bg, lv.bar),
        "menu, .menu, .context-menu, #gtk-combobox-popup-menu, popover, popover.background,",
        "tooltip, tooltip.background { background-color: %s; }" % rgba(bg, 1.0),
        END,
        ""])


def drop_block(text):
    out, skip = [], False
    for ln in text.splitlines(keepends=True):
        s = ln.strip()
        if s == BEGIN:
            skip = True
            continue
        if skip:
            if s == END:
                skip = False
            continue
        out.append(ln)
    # no end marker (cut by hand): skipping to EOF would drop the user's rules
    if skip:
        raise Conflict("appglass begin line has no end line; left untouched")
    res = "".join(out)
    return res.rstrip("\n") + "\n" if res.strip() else ""


def edit(text, blk):
    base = drop_block(text)
    if base and not base.endswith("\n\n"):
        base += "\n"
    return base + blk


def undo(env, path, text):
    return drop_block(text)


def apply(ctx):
    env = ctx.env
    vs = versions(env)
    if not vs:
        ctx.warn("gimp: version not known (no gimp --version, no metainfo, no ~/.config/GIMP/<x.y>)")
        return []
    paths = []
    for v in vs:
        d = os.path.join(env.config_home, "GIMP", v)
        css = os.path.join(d, "gimp.css")
        if os.path.islink(css):
            raise Conflict("%s is a symlink (user-managed); left untouched" % css)
        try:
            with open(os.path.join(d, "gimprc"), encoding="utf-8", errors="replace") as f:
                rc = f.read()
        except OSError:
            rc = ""
        m = re.search(r'\(theme\s+"([^"]+)"\)', rc)
        if m and m.group(1) != "Default":
            ctx.warn_once("gimp-theme-" + v, "gimp %s: theme %r is not Default: the glass "
                          "block uses the Default theme's colours" % (v, m.group(1)))
        blk = block(ctx, colours(env, scheme(rc)))
        ctx.edit_text(css, lambda text, b=blk: edit(text, b), undo=lambda text, p=css: undo(env, p, text))
        paths.append(css)
    return paths
