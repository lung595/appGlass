#!/usr/bin/env python3
"""Compile glass.vert / glass.frag to SPIR-V and write glass-spv.h (the arrays the layer embeds).

No glslc or glslangValidator is needed: this calls libshaderc_shared (Fedora: libshaderc) through
ctypes. The header records the sha256 of both sources, so a test can tell when it is stale.

    gen-spv.py           write glass-spv.h
    gen-spv.py --check   exit 1 if glass-spv.h is not what this would write
                         (only compared byte for byte when the installed compiler is the one
                         that wrote it: another glslang version may emit other, equally valid code)
"""

import ctypes
import hashlib
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "glass-spv.h")
SOURCES = (("glass.vert", 0, "glass_vert_spv"), ("glass.frag", 1, "glass_frag_spv"))  # shaderc kind
VULKAN, VULKAN_1_1 = 0, (1 << 22) | (1 << 12)
OPT_PERFORMANCE = 2


def lib():
    for n in ("libshaderc_shared.so.1", "libshaderc_shared.so"):
        try:
            s = ctypes.CDLL(n)
            break
        except OSError:
            s = None
    if s is None:
        sys.exit("libshaderc_shared not found (dnf install libshaderc)")
    s.shaderc_compiler_initialize.restype = ctypes.c_void_p
    s.shaderc_compile_options_initialize.restype = ctypes.c_void_p
    s.shaderc_compile_options_set_target_env.argtypes = [ctypes.c_void_p, ctypes.c_int, ctypes.c_uint32]
    s.shaderc_compile_options_set_optimization_level.argtypes = [ctypes.c_void_p, ctypes.c_int]
    s.shaderc_compile_into_spv.restype = ctypes.c_void_p
    s.shaderc_compile_into_spv.argtypes = [ctypes.c_void_p, ctypes.c_char_p, ctypes.c_size_t, ctypes.c_int,
                                           ctypes.c_char_p, ctypes.c_char_p, ctypes.c_void_p]
    for f in ("get_compilation_status", "get_length", "get_bytes", "get_error_message", "release"):
        getattr(s, "shaderc_result_" + f).argtypes = [ctypes.c_void_p]
    s.shaderc_result_get_length.restype = ctypes.c_size_t
    s.shaderc_result_get_bytes.restype = ctypes.c_void_p
    s.shaderc_result_get_error_message.restype = ctypes.c_char_p
    return s


def compile_all():
    s = lib()
    comp, opts = s.shaderc_compiler_initialize(), s.shaderc_compile_options_initialize()
    s.shaderc_compile_options_set_target_env(opts, VULKAN, VULKAN_1_1)
    s.shaderc_compile_options_set_optimization_level(opts, OPT_PERFORMANCE)
    h, out = hashlib.sha256(), []
    for name, kind, sym in SOURCES:
        with open(os.path.join(HERE, name), "rb") as f:
            text = f.read()
        h.update(text)
        r = s.shaderc_compile_into_spv(comp, text, len(text), kind, name.encode(), b"main", opts)
        if s.shaderc_result_get_compilation_status(r) != 0:
            sys.exit("%s: %s" % (name, s.shaderc_result_get_error_message(r).decode()))
        n = s.shaderc_result_get_length(r)
        data = ctypes.string_at(s.shaderc_result_get_bytes(r), n)
        s.shaderc_result_release(r)
        out.append((name, sym, [int.from_bytes(data[i:i + 4], "little") for i in range(0, n, 4)]))
    return h.hexdigest(), out


def render(digest, shaders):
    lines = ["// Generated by gen-spv.py from glass.vert and glass.frag. Do not edit: run gen-spv.py.",
             "// sources sha256 %s" % digest, "#include <stdint.h>"]
    for name, sym, words in shaders:
        lines.append("static const uint32_t %s[] = {  /* %s */" % (sym, name))
        for i in range(0, len(words), 8):
            lines.append("    " + ", ".join("0x%08x" % w for w in words[i:i + 8]) + ",")
        lines.append("};")
    return "\n".join(lines) + "\n"


def main():
    digest, shaders = compile_all()
    text = render(digest, shaders)
    if "--check" in sys.argv[1:]:
        try:
            with open(OUT) as f:
                old = f.read()
        except OSError:
            sys.exit("glass-spv.h missing")
        if "// sources sha256 %s" % digest not in old:
            sys.exit("glass-spv.h is stale: run gen-spv.py")
        gen = "0x%08x" % shaders[0][2][2]     # SPIR-V header word 2: generator id and version
        if gen in old.split("{", 2)[1][:200] and old != text:
            sys.exit("glass-spv.h differs from this compiler's output: run gen-spv.py")
        return
    with open(OUT, "w") as f:
        f.write(text)


if __name__ == "__main__":
    main()
